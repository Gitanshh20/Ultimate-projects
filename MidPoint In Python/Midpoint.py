# Midpoint in Python

x1 = float(input("Enter Your x1 co: "))
x2 = float(input("Enter Your x2 co: "))
y1 = float(input("Enter Your y1 co: "))
y2 = float(input("Enter Your y2 co: "))

# Midpoint for x and y

x = (x1 + x2)/2
y = (y1 + y2)/2

# Cordinates are

print(f"Your Midpoint is: ({x}, {y})")